namespace AssetForge.Core
{
    /// <summary>
    /// Represents AssetForge version
    /// </summary>
    public static class AssetForgeVersion
    {
        /// <summary>
        /// Gets the major Site version
        /// </summary>
        public const string CURRENT_VERSION = "1.0000";

        /// <summary>
        /// Gets the minor Site version
        /// </summary>
        public const string MINOR_VERSION = "1";

        /// <summary>
        /// Gets the full Site version
        /// </summary>
        public const string FULL_VERSION = CURRENT_VERSION + "." + MINOR_VERSION;
    }
}
